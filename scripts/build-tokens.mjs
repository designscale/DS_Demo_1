// Generates src/tokens/tokens.css from src/tokens/tokens.json.
// tokens.json mirrors the Figma variable collections and modes, so updating a
// value there (or re-exporting from Figma) and running `npm run tokens` keeps
// code and design in sync.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'src/tokens/tokens.json'), 'utf8'));

const px = (n) => `${n}px`;
const primitiveVar = (ref) => {
  // "neutral.800" -> var(--color-neutral-800)
  const [group, step] = ref.split('.');
  return `var(--color-${group}-${step})`;
};

// Walk nested semantic color tokens and collect { name, light, dark }.
function flattenColors(node, path = []) {
  const out = [];
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value && typeof value === 'object' && 'light' in value) {
      out.push({ name: [...path, key].join('-'), ...value });
    } else if (value && typeof value === 'object') {
      out.push(...flattenColors(value, [...path, key]));
    }
  }
  return out;
}

const lines = [];
const push = (s = '') => lines.push(s);

push('/* AUTO-GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */');
push();

// ---------- :root (primitives, light theme, sm type scale) ----------
push(':root {');
push('  /* color primitives */');
for (const [group, steps] of Object.entries(tokens['color-primitives'])) {
  for (const [step, hex] of Object.entries(steps)) push(`  --color-${group}-${step}: ${hex};`);
}
push();
push('  /* space primitives */');
for (const [step, value] of Object.entries(tokens.space)) push(`  --space-${step}: ${px(value)};`);
push();
push('  /* radius */');
for (const [step, value] of Object.entries(tokens.radius)) push(`  --radius-${step}: ${px(value)};`);
push();
const text = tokens['text-primitives'];
push('  /* text primitives */');
for (const [name, family] of Object.entries(text['font-family'])) {
  push(`  --font-family-${name}: '${family}', system-ui, -apple-system, 'Segoe UI', sans-serif;`);
}
for (const [name, weight] of Object.entries(text['font-weight'])) push(`  --font-weight-${name}: ${weight};`);
for (const [step, modes] of Object.entries(text['font-size'])) push(`  --font-size-${step}: ${px(modes.sm)};`);
push('}');
push();

const colors = flattenColors(tokens.color);
const themeBlock = (selector, mode) => {
  push(`${selector} {`);
  for (const c of colors) push(`  --color-${c.name}: ${primitiveVar(c[mode])};`);
  push('}');
  push();
};
push('/* Semantic colors: Figma collection "color", mode light (default) */');
themeBlock(':root, [data-theme="light"]', 'light');
push('/* Semantic colors: Figma collection "color", mode dark */');
themeBlock('[data-theme="dark"]', 'dark');

// ---------- responsive type scale (Figma modes sm / md / lg) ----------
const sizeDecls = (mode, indent) =>
  Object.entries(text['font-size']).map(([step, modes]) => `${indent}--font-size-${step}: ${px(modes[mode])};`);

push('/* Type scale modes. Page level: viewport media queries. */');
for (const [mode, min] of [['md', 800], ['lg', 1280]]) {
  push(`@media (min-width: ${min}px) {`);
  push('  :root {');
  sizeDecls(mode, '    ').forEach((l) => push(l));
  push('  }');
  push('}');
}
push();
push('/* Component level: every DS component is a `ds` container, so the type');
push('   scale follows the width the component is rendered at (like switching the');
push('   text collection mode on a Figma frame). */');
for (const [mode, min] of [['sm', 0], ['md', 800], ['lg', 1280]]) {
  push(`@container ds (min-width: ${min}px) {`);
  push('  * {');
  sizeDecls(mode, '    ').forEach((l) => push(l));
  push('  }');
  push('}');
}
push();

// ---------- text styles as utility classes ----------
push('/* Figma text styles */');
for (const [name, style] of Object.entries(tokens.font)) {
  if (name.startsWith('$')) continue;
  const cls = `ds-font-${name.replace(/\//g, '-')}`;
  push(`.${cls} {`);
  push('  font-family: var(--font-family-sans);');
  push(`  font-size: var(--font-size-${style.size});`);
  push(`  font-weight: var(--font-weight-${style.weight});`);
  push(`  line-height: ${style.lineHeight};`);
  push(`  letter-spacing: ${style.letterSpacing === 0 ? 0 : `${style.letterSpacing / 100}em`};`);
  push('}');
}
push();

writeFileSync(resolve(root, 'src/tokens/tokens.css'), lines.join('\n'));
console.log(`tokens.css written (${colors.length} semantic colors, ${Object.keys(tokens.font).length - 1} text styles)`);
